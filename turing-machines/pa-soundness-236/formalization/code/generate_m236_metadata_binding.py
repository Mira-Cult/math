#!/usr/bin/env python3
"""Generate untrusted byte witnesses for the retained M236 producer metadata.

Lean checks the full character witness, file decomposition, every relevant
JSON row, and the graph/table relations. This script is not part of the trust
boundary; --check verifies reproducibility of the checked-in witnesses.
"""
import argparse
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / 'bindings/m236/producer-metadata.json'
output = root / 'lean/PASoundness'
data = source.read_bytes()
if hashlib.sha256(data).hexdigest() != 'cfd15b5d5eb62357ee4a9808d6e3cf044eab9ff2fdcbc1e8f0880046c5d4752e':
    raise ValueError('unexpected metadata')
text = data.decode('ascii')
d = json.loads(text)

def bounds(key):
    marker = f'  "{key}": {{\n'
    start = text.index(marker) + len(marker)
    end = text.index('\n  },\n', start)
    return start, end

def nums(data):
    return '[' + ', '.join(str(b) for b in data) + ']'

def lit(s):
    return json.dumps(s, ensure_ascii=True)

g0, g1 = bounds('grammar')
n0, n1 = bounds('grammar_names')
s0, s1 = bounds('named_state_to_id')
root_line = '  "grammar_root": 157,\n'
r0 = text.index(root_line, n1, s0); r1 = r0 + len(root_line)
dispatch = '  "run_dispatch": {\n    "leaf_paths": 760,\n    "max_zero_run": 5,\n    "prefix": "110",\n    "threshold": 6\n  },\n'
d0 = text.index(dispatch, s1); d1 = d0 + len(dispatch)
parts = [text[:g0], text[g1:n0], text[n1:r0], text[r1:s0], text[s1:d0], text[d1:]]

grammar_items = [f'    {lit(k)}: [\n      {lit(v[0])},\n      {lit(v[1])}\n    ]'
                 for k, v in d['grammar'].items()]
name_items = [f'    {lit(k)}: {lit(v)}' for k, v in d['grammar_names'].items()]
state_items = [f'    {lit(k)}: {v}' for k, v in d['named_state_to_id'].items()]
for (a, b), items in [((g0, g1), grammar_items), ((n0, n1), name_items), ((s0, s1), state_items)]:
    if ',\n'.join(items) != text[a:b]:
        raise ValueError('unexpected JSON layout')

names = [''] * 237
for name, state in d['named_state_to_id'].items():
    if not 0 <= state < 237 or names[state]:
        raise ValueError('invalid state map')
    names[state] = name
if any(not n for n in names):
    raise ValueError('incomplete state map')
if any(any(ord(c) < 32 or c in '\\"' for c in name) for name in names):
    raise ValueError('unsupported JSON escaping')

grammar_order = [int(k) for k in d['grammar']]
name_order = [int(k) for k in d['grammar_names']]
state_order = list(d['named_state_to_id'].values())
if grammar_order != name_order:
    raise ValueError('grammar and name orders differ')

metadata_names = '''import PASoundness.M236GrammarData

/-! Generated name and ordering witnesses; the metadata binding checks them. -/
namespace PASoundness.M236.Metadata
'''
metadata_names += 'def grammarOrder : List (Fin 158) := [' + ', '.join(map(str, grammar_order)) + ']\n'
metadata_names += 'def stateOrder : List (Fin 237) := [' + ', '.join(map(str, state_order)) + ']\n'
metadata_names += 'def stateNames : Vector String 237 := #v[\n  ' + ',\n  '.join(map(lit, names)) + '\n]\n'
metadata_names += 'end PASoundness.M236.Metadata\n'

witness = '''import PASoundness.M236MetadataFormat

/-! Generated byte witnesses. Their connection to the embedded file and to the
Lean grammar is checked in M236MetadataText. -/
set_option maxRecDepth 524288
set_option maxHeartbeats 0
namespace PASoundness.M236.Metadata
open PASoundness.M236.TextEncoding
'''
witness += 'def fileBytes : List UInt8 := ' + nums(data) + '\n'
for i, part in enumerate(parts):
    witness += f'def part{i} : List UInt8 := {nums(part.encode())}\n'
for name, items in [('grammarWitness', grammar_items), ('nameWitness', name_items), ('stateWitness', state_items)]:
    witness += f'def {name} : List (List UInt8) := [\n  ' + ',\n  '.join(nums(x.encode()) for x in items) + '\n]\n'
witness += 'def rootWitness : List UInt8 := ' + nums(root_line.encode()) + '\n'
witness += 'def dispatchWitness : List UInt8 := ' + nums(dispatch.encode()) + '\n'
witness += '''
theorem assembled : fileBytes =
    part0 ++ List.intercalate separator grammarWitness ++ part1 ++
    List.intercalate separator nameWitness ++ part2 ++ rootWitness ++ part3 ++
    List.intercalate separator stateWitness ++ part4 ++ dispatchWitness ++ part5 := by rfl

theorem grammar_rows : grammarWitness = grammarRows := by decide

theorem name_rows : nameWitness = nameRows := by decide

theorem state_rows : stateWitness = stateRows := by decide

theorem root_row : rootWitness = bytes rootText := by decide

theorem dispatch_row : dispatchWitness = bytes dispatchText := by decide

end PASoundness.M236.Metadata
'''

parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
for filename, content in [('M236MetadataNames.lean', metadata_names), ('M236MetadataWitness.lean', witness)]:
    path = output / filename
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f'generated source differs: {path}')
    elif not path.exists() or path.read_text() != content:
        path.write_text(content)
print('generated exact M236 producer metadata witnesses')
