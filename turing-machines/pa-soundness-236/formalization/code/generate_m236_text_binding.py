#!/usr/bin/env python3
"""Generate untrusted explicit file bytes and row witnesses for Lean checks."""
from __future__ import annotations
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'lean/PASoundness'
CASES = [
    ('Selected', 'machine.tm', 'machine', 'machineLabels', 236,
     'bcf4a1fd22e9959a4145688d05ec20591d97967050ad1a16beeb22a187edaedc'),
    ('Raw', 'raw.tm', 'raw', 'rawLabels', 237,
     'e73b3c7fbcbbc4614e4ee33a6e33cacfb3b8e2dc32822591db2afdfedf01a9e8'),
]

def literal(data):
    return '[' + ', '.join(str(x) for x in data) + ']'

def generate(case):
    name, filename, machine, labels, states, digest = case
    source = (ROOT / 'bindings/m236' / filename).read_bytes()
    if hashlib.sha256(source).hexdigest() != digest:
        raise ValueError(f'{filename}: input digest mismatch')
    lines = source.splitlines(keepends=True)
    if len(lines) != 5 + 2 * states or any(not s.endswith(b'\n') for s in lines):
        raise ValueError(f'{filename}: unexpected line count or termination')
    text = '''import PASoundness.M236TextEncoding

/-! Generated byte witnesses. Lean checks the file bytes, the headers, every
row, and the composition; this generator is not part of the trusted proof. -/
set_option maxRecDepth 65536
set_option maxHeartbeats 0
'''
    text += f'namespace PASoundness.M236.TableRows{name}\n'
    text += 'open PASoundness.M236.TextEncoding\n\n'
    text += f'def fileBytes : List UInt8 := {literal(source)}\n'
    text += f'def headerBytes : List UInt8 := {literal(b"".join(lines[:5]))}\n'
    text += 'def literalRows : List (List UInt8) := [\n  ' + ',\n  '.join(map(literal, lines[5:])) + '\n]\n\n'
    text += '''theorem assembled : fileBytes = headerBytes ++ literalRows.flatten := by rfl

'''
    text += f'theorem header_checked : headerBytes = bytes (headerText {machine}) := by decide\n\n'
    text += f'theorem rows_checked : literalRows = rows {machine} {labels} := by decide\n\n'
    text += f'end PASoundness.M236.TableRows{name}\n'
    binding = f'''import PASoundness.M236TableRows{name}
import PASoundness.M236Ascii

set_option maxRecDepth 131072
set_option maxHeartbeats 0
namespace PASoundness.M236.TableText{name}
open PASoundness.M236.TextEncoding PASoundness.M236.TableRows{name}

def input : String := include_str ".." / ".." / "bindings" / "m236" / "{filename}"

/-- The embedded file has exactly these characters. Recompile after changing
the external input; this is an equality, not a digest comparison. -/
theorem input_chars :
    input = String.ofList (fileBytes.map fun b => Char.ofNat b.toNat) := by rfl

theorem ascii_checked : fileBytes.all (fun b => decide (b.toNat < 128)) = true := by decide

theorem input_checked : input.toByteArray = ⟨⟨fileBytes⟩⟩ := by
  rw [input_chars, String.toByteArray_ofList]
  apply PASoundness.M236.Ascii.encode_list
  intro b hb
  exact of_decide_eq_true ((List.all_eq_true.mp ascii_checked) b hb)

/-- Exact retained file bytes equal the serialization of the Lean
machine, including every input, write, movement, target and event label. -/
theorem binding : bytes input = tableBytes {machine} {labels} := by
  unfold bytes tableBytes
  rw [input_checked]
  change fileBytes = _
  rw [assembled, header_checked, rows_checked]

end PASoundness.M236.TableText{name}
'''
    return text, binding

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for case in CASES:
        values = generate(case)
        for kind, value in zip(('Rows', 'Text'), values):
            path = OUT / f'M236Table{kind}{case[0]}.lean'
            if args.check:
                if not path.exists() or path.read_text() != value:
                    raise SystemExit(f'generated source differs: {path}')
            elif not path.exists() or path.read_text() != value:
                path.write_text(value)
    print('generated exact raw and selected file/row witnesses')

if __name__ == '__main__':
    main()
