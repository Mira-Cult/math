#!/usr/bin/env python3
"""Generate the greedy scan-compressed trace up to the first bootstrap exit.

The generated actions are untrusted certificate input; Lean's replay checker
must independently accept them to establish a physical-machine statement.
"""
from __future__ import annotations

import argparse
from pathlib import Path


def generate() -> tuple[list[tuple[str, int]], list[tuple[int, int, int]]]:
    path = Path(__file__).parent / "Inputs" / "selected284-events.tm"
    rows: dict[tuple[int, int], tuple[int, str, int, int]] = {}
    for line in path.read_text(encoding="ascii").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        q, read, write, direction, target, beep = line.split()
        key = int(q), int(read)
        assert key not in rows
        assert direction in ("L", "R") and write in ("0", "1") and beep in ("0", "1")
        rows[key] = int(write), direction, int(target), int(beep)
    assert set(rows) == {(q, b) for q in range(284) for b in (0, 1)}
    ones: set[int] = set()
    q = head = steps = 0
    ops: list[tuple[str, int]] = []
    checkpoints = [(q, head, steps)]
    while q in (0, 2, 3, 4, 5):
        count = 0
        if q == 4:
            while head in ones and head + 1 not in ones:
                head += 2
                count += 1
            op = "right"
        elif q in (0, 2):
            op = "fill" if q == 0 else "left"
            while head in ones and head - 1 not in ones:
                if q == 2:
                    ones.remove(head)
                ones.add(head - 1)
                head -= 2
                count += 1
        if count:
            ops.append((op, count))
            steps += 2 * count
        else:
            write, direction, q, beep = rows[q, int(head in ones)]
            assert beep == 0
            if write:
                ones.add(head)
            else:
                ones.discard(head)
            head += 1 if direction == "R" else -1
            ops.append(("single", 0))
            steps += 1
        checkpoints.append((q, head, steps))
    assert (q, head, steps) == (261, -2, 2_133_492)
    assert ones == set(range(-3821, -2, 2)) | {-2, 0, 1, 2, 3}
    return ops, checkpoints


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lean", action="store_true", help="print Lean certificate data")
    args = parser.parse_args()
    ops, checkpoints = generate()
    if args.lean:
        print("import Shared.Beeping.NPcoNP.Bootstrap284Certificate")
        print("\n/-! Generated by generate_bootstrap284_trace.py --lean. Untrusted input. -/")
        print("namespace Shared.Beeping.NPcoNP.Bootstrap284TraceData")
        print("open Shared.Beeping.NPcoNP.Bootstrap284Certificate")
        print("set_option maxRecDepth 32768")
        print("def ops : List Op := [")
        for i in range(0, len(ops), 8):
            items = [".single" if op == "single" else f".{op} {n}" for op, n in ops[i:i+8]]
            suffix = "," if i + 8 < len(ops) else ""
            print("  " + ", ".join(items) + suffix)
        print("]\nend Shared.Beeping.NPcoNP.Bootstrap284TraceData")
    else:
        print(f"{len(ops)} actions, {checkpoints[-1][2]} physical transitions")
        for count in (16, 32, 64, 128, 256):
            print(f"first {count}: state,head,time = {checkpoints[count]}")
        print("first-exit tape and final checkpoint match the independent literal control")


if __name__ == "__main__":
    main()
