"""Generate a kernel-checkable complete character listing of the grammar.

The generated Lean equality checks the entire `include_str` value against
the listing, including its final newline. It does not prove anything about a
later change to the filesystem, the SHA-256 implementation, or JSON parsing.
"""
import argparse
import hashlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "Inputs" / "parent290-grammar.json"
SOURCE_SHA256 = "6520062bc16643402072f386590392688ed6cb47e509a6b98dc5acb982d6b9d3"


def char_literal(char: str) -> str:
    escapes = {"\n": r"\n", "\r": r"\r", "\t": r"\t",
               "'": r"\'", "\\": r"\\"}
    return "'" + escapes.get(char, char) + "'"


def generate() -> str:
    data = SOURCE.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SOURCE_SHA256:
        raise ValueError(f"unexpected source SHA-256: {digest}")
    text = data.decode("ascii")
    if not text.endswith("\n") or not all(c in "\n\r\t" or 32 <= ord(c) < 127 for c in text):
        raise ValueError("expected printable ASCII text ending in a newline")
    chars = ", ".join(map(char_literal, text))
    return ("import Std\n\n"
            "/-! Complete character content of the pinned ASCII input as embedded\n"
            "by `include_str`, including the final newline. This equality is\n"
            "kernel-checked; JSON-to-AST and any later filesystem state remain\n"
            "separate. Generated by `generate_grammar_source_chars.py`. -/\n"
            "namespace Shared.Beeping.NPcoNP.Grammar284.SourceChars\n\n"
            "set_option maxRecDepth 1000000\n"
            "set_option maxHeartbeats 0\n\n"
            "def source : String := include_str \"Inputs/parent290-grammar.json\"\n\n"
            "def chars : List Char := [" + chars + "]\n\n"
            "theorem source_eq_ofList : source = String.ofList chars := by rfl\n\n"
            "theorem source_toList : source.toList = chars := by\n"
            "  rw [source_eq_ofList, String.toList_ofList]\n\n"
            "end Shared.Beeping.NPcoNP.Grammar284.SourceChars\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=HERE / "Grammar284SourceChars.lean")
    args = parser.parse_args()
    args.output.write_text(generate(), encoding="utf-8")


if __name__ == "__main__":
    main()
