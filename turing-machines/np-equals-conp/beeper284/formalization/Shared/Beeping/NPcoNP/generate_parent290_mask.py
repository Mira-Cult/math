"""Recover retained register rows and masks from the pinned producer certificate.

This executable generator is evidence and a reproduction aid, not a Lean
proof that the generated data implement the source grammar or physical table.
The path-walking algorithm was cross-checked against the independent
check_closed_regions.py extraction used for the 284 producer review.
"""
from pathlib import Path
import hashlib
import json

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "Inputs/parent290-coalescence-invariant.json"
DESTINATION = HERE / "Parent290MaskData.lean"
SOURCE_SHA256 = "59c0514648abb461928bd877a4bc2d1da92f652050803544ad2ffd03906432f2"


def extract(certificate):
    grammar = certificate["input_grammar"]
    nodes, root, registers = grammar["nodes"], grammar["root"], grammar["registers"]
    occurrences = []

    def visit(node, prefix):
        for bit, child in enumerate(nodes[node]):
            path = prefix + (bit,)
            if "node" in child:
                assert child["node"] < node
                visit(child["node"], path)
            else:
                assert set(child) == {"op"}
                occurrences.append((path, child["op"]))

    visit(root, (1, 1, 0))
    indices = {path: i for i, (path, _) in enumerate(occurrences)}
    assert len(indices) == len(occurrences) == 279
    states = certificate["states_at_occurrences"]
    assert len(states) == 279 and len(registers) == 15 and len(set(registers)) == 15

    def jump(path, continuing, count):
        target = int(continuing)
        for pos in range(len(path) - 1, -1 if continuing else 1, -1):
            if path[pos] == target:
                if count:
                    count -= 1
                else:
                    return path[:pos] + (1,)
        raise ValueError("escaped root")

    def resolve(path):
        path = list(path)
        if path[:3] == [1, 1, 1]:
            path = [1, 1, 0]
        assert path[:3] == [1, 1, 0]
        node, pos = root, 3
        while True:
            if pos == len(path):
                path.append(0)
            child = nodes[node][path[pos]]
            pos += 1
            if "op" in child:
                assert pos == len(path)
                return tuple(path), child["op"]
            node = child["node"]

    def retained(path):
        seen = set()
        while True:
            path, op = resolve(path)
            assert path not in seen, "administrative-only cycle"
            seen.add(path)
            if not op.startswith("_"):
                return path
            kind, count = op[1:].split(".")
            assert kind in ("break", "continue")
            path = jump(path, kind == "continue", int(count))

    kept = [(path, op) for path, op in occurrences if not op.startswith("_")]
    assert len(kept) == 185
    kept_index = {path: i for i, (path, _) in enumerate(kept)}
    start = kept_index[retained((1, 1, 0))]
    rows, masks = [], []
    for path, op in kept:
        first = kept_index[retained(jump(path, False, 0))]
        if op == "beep":
            action, second = ".base (.emit true)", first
        else:
            assert op.startswith("3.")
            name, code = op[2:].rsplit(".", 1)
            half = name.startswith("$native-half:")
            if half:
                name = name[len("$native-half:"):]
            reg = registers.index(name)
            if half:
                assert code == "decnz"
                action = f".half {reg}"
            elif code == "inc":
                action = f".base (.inc {reg})"
            else:
                assert code == "decnz"
                action = f".base (.decNZ {reg})"
            second = kept_index[retained(jump(path, False, 1))] if code == "decnz" else first
        state = states[indices[path]]
        assert state is not None and len(state) == 15 and set(state) <= set("1234567")
        rows.append((action, first, second))
        masks.append([int(x) for x in state])

    # On native HALF, successor 0 is odd/success; successor 1 is even/failure.
    assert rows[70] == (".half 3", 71, 77)
    assert rows[161] == (".half 3", 162, 168)
    assert all(masks[i][q] == 1 for i in (70, 161) for q in (6, 9))
    return start, rows, masks


def render(start, rows, masks):
    lines = [
        "import Shared.Beeping.NPcoNP.MaskInvariantCheck", "",
        "/-! Generated by `generate_parent290_mask.py` from the pinned parent290",
        "certificate. Its correspondence to source bytes and to the 284-state",
        "table remains unproved in Lean. -/", "",
        "namespace Shared.Beeping.NPcoNP.Parent290MaskData",
        "open Shared.Beeping.NPcoNP.AbstractMasks",
        "open Shared.Beeping.NPcoNP.MaskInvariant", "",
        "def program : Program 15 185 where", "  code := #v[",
    ]
    lines.extend(f"    ⟨{action}, {yes}, {no}⟩," for action, yes, no in rows)
    lines[-1] = lines[-1].removesuffix(",")
    lines.extend(["  ]", f"  start := {start}", "", "def maskDigits : Vector (Vector Nat 15) 185 := #v["])
    lines.extend("  #v[" + ", ".join(map(str, row)) + "]," for row in masks)
    lines[-1] = lines[-1].removesuffix(",")
    lines.extend([
        "]", "", "def digitMask : Nat → Mask",
        "  | 0 => ∅", "  | 1 => {Category.zero}", "  | 2 => {Category.one}",
        "  | 3 => {Category.zero, Category.one}", "  | 4 => {Category.many}",
        "  | 5 => {Category.zero, Category.many}", "  | 6 => {Category.one, Category.many}",
        "  | _ => {Category.zero, Category.one, Category.many}", "",
        "def masks : Fin 185 → MaskBank 15 := fun s q => digitMask maskDigits[s][q]", "",
        "end Shared.Beeping.NPcoNP.Parent290MaskData", "",
    ])
    return "\n".join(lines)


def main():
    raw = SOURCE.read_bytes()
    assert hashlib.sha256(raw).hexdigest() == SOURCE_SHA256
    start, rows, masks = extract(json.loads(raw))
    DESTINATION.write_text(render(start, rows, masks))
    print(f"source_sha256={SOURCE_SHA256} start={start} rows={len(rows)} registers=15")


if __name__ == "__main__":
    main()
