#!/usr/bin/env python3
"""Run preserved certificate generators in a temporary copy and compare bytes.

No generated proof certificate is trusted without Lean checking it. The
temporary copy may contain diagnostic outputs outside the selected closure.
"""
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

ROOT=Path(__file__).resolve().parent

# Record the files a generator writes without changing the bytes it writes.
DRIVER='''import json, pathlib, runpy, sys
log, script, *args = sys.argv[1:]
seen=[]
orig_text=pathlib.Path.write_text
orig_bytes=pathlib.Path.write_bytes
def write_text(self,*a,**kw):
 seen.append(str(self.resolve())); return orig_text(self,*a,**kw)
def write_bytes(self,*a,**kw):
 seen.append(str(self.resolve())); return orig_bytes(self,*a,**kw)
pathlib.Path.write_text=write_text
pathlib.Path.write_bytes=write_bytes
sys.argv=[script,*args]
sys.path.insert(0,str(pathlib.Path(script).resolve().parent))
runpy.run_path(script,run_name="__main__")
orig_text(pathlib.Path(log),json.dumps(seen))
'''

def main():
    recipes=json.loads((ROOT/'GENERATOR-RECIPES.json').read_text())
    compared=set();diagnostic=set()
    with tempfile.TemporaryDirectory(prefix='npconp284-regenerate-') as temporary:
        temp=Path(temporary)/'formalization'
        shutil.copytree(ROOT/'formalization',temp,ignore=shutil.ignore_patterns('.lake','__pycache__'))
        for index,recipe in enumerate(recipes):
            log=Path(temporary)/f'writes-{index}.json'
            result=subprocess.run([sys.executable,'-c',DRIVER,str(log),recipe['script'],*recipe.get('arguments',[])],
                                  cwd=temp,check=True,capture_output=True)
            paths=[Path(p) for p in json.loads(log.read_text())]
            if 'stdout' in recipe:
                output=temp/recipe['stdout'];output.parent.mkdir(parents=True,exist_ok=True)
                output.write_bytes(result.stdout);paths.append(output)
            matching=[]
            for path in paths:
                if not path.is_relative_to(temp):raise ValueError('Generator wrote outside temporary project: '+str(path))
                rel=path.relative_to(temp);original=ROOT/'formalization'/rel
                if not original.is_file():diagnostic.add(str(rel));continue
                if path.read_bytes()!=original.read_bytes():raise ValueError('Generated bytes differ: '+str(rel))
                matching.append(str(rel));compared.add(str(rel))
            if not matching:raise ValueError('Recipe regenerated no released file: '+recipe['script'])
            print(f'PASS: {recipe["script"]} ({len(set(matching))} released files)')
    print(f'PASS: {len(recipes)} recipes reproduced {len(compared)} distinct released Lean sources byte for byte.')
    print(f'{len(diagnostic)} additional diagnostic outputs are outside the released import closure.')

if __name__=='__main__':main()
