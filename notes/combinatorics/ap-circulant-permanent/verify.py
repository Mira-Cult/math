"""Deterministic, exact regression checks; no third-party dependencies.

Subset assignment DP and permutation enumeration are independent references.
The finite tests are not a substitute for the invariant proof in README.md.
"""

from fractions import Fraction
from itertools import permutations, product
from math import factorial, prod
from random import Random
import json

from permanent import permanent_ap_circulant, permanent_staircase


def subset_permanent(matrix):
    n = len(matrix)
    dp = [0] * (1 << n)
    dp[0] = 1
    for mask in range(1, 1 << n):
        i = mask.bit_count() - 1
        dp[mask] = sum(dp[mask ^ (1 << j)] * matrix[i][j]
                       for j in range(n) if mask >> j & 1)
    return dp[-1]


def permutation_permanent(matrix):
    return sum(prod(matrix[i][j] for i, j in enumerate(p))
               for p in permutations(range(len(matrix))))


def circulant(n, a, b):
    return [[a + b * ((j - i) % n) for j in range(n)] for i in range(n)]


def staircase(u, v, t):
    return [[x + y + t * (j < i) for j, y in enumerate(v)]
            for i, x in enumerate(u)]


class Residue:
    """Small exact Z/mZ test object, including composite characteristics."""

    def __init__(self, value, modulus):
        self.value = value % modulus
        self.modulus = modulus

    def coerce(self, value):
        if isinstance(value, Residue):
            assert value.modulus == self.modulus
            return value.value
        return value

    def __add__(self, other):
        return Residue(self.value + self.coerce(other), self.modulus)

    __radd__ = __add__

    def __mul__(self, other):
        return Residue(self.value * self.coerce(other), self.modulus)

    __rmul__ = __mul__

    def __sub__(self, other):
        return Residue(self.value - self.coerce(other), self.modulus)

    def __eq__(self, other):
        return self.value == self.coerce(other) % self.modulus


def main():
    rng = Random(3708)
    counts = {}

    counts["signed_ap_grid"] = 0
    for n in range(8):
        for a, b in product(range(-3, 4), repeat=2):
            matrix = circulant(n, a, b)
            actual = permanent_ap_circulant(n, a, b)
            assert actual == subset_permanent(matrix), (n, a, b)
            if n <= 5:
                assert actual == permutation_permanent(matrix)
            assert permanent_ap_circulant(n, -a - (n-1)*b, b) == (-1)**n * actual
            counts["signed_ap_grid"] += 1

    counts["rational_ap"] = 0
    for n in range(10):
        for _ in range(15):
            a = Fraction(rng.randint(-15, 15), rng.randint(1, 9))
            b = Fraction(rng.randint(-15, 15), rng.randint(1, 9))
            assert permanent_ap_circulant(n, a, b) == subset_permanent(circulant(n, a, b))
            counts["rational_ap"] += 1

    counts["signed_general"] = 0
    for n in range(9):
        for _ in range(20):
            u = [rng.randint(-5, 5) for _ in range(n)]
            v = [rng.randint(-5, 5) for _ in range(n)]
            t = rng.randint(-5, 5)
            matrix = staircase(u, v, t)
            actual = permanent_staircase(u, v, t)
            assert actual == subset_permanent(matrix), (u, v, t)
            if n <= 6:
                assert actual == permutation_permanent(matrix)
            counts["signed_general"] += 1

    counts["rational_general"] = 0
    for n in range(8):
        for _ in range(12):
            def rat():
                return Fraction(rng.randint(-8, 8), rng.randint(1, 11))
            u, v = [rat() for _ in range(n)], [rat() for _ in range(n)]
            t = rat()
            assert permanent_staircase(u, v, t) == subset_permanent(staircase(u, v, t))
            counts["rational_general"] += 1

    counts["finite_ring_general"] = 0
    for modulus in (2, 3, 4, 6, 9, 11, 25):
        for n in range(7):
            for _ in range(8):
                u = [rng.randint(-9, 9) for _ in range(n)]
                v = [rng.randint(-9, 9) for _ in range(n)]
                t = rng.randint(-9, 9)
                actual = permanent_staircase([Residue(x, modulus) for x in u],
                                             [Residue(x, modulus) for x in v],
                                             Residue(t, modulus))
                expected = subset_permanent(staircase(u, v, t)) % modulus
                assert actual == expected, (modulus, u, v, t)
                counts["finite_ring_general"] += 1

    # Published OEIS A086759 values, not generated by the tested implementation.
    values = [0, 1, 9, 164, 5050, 227508, 14064519, 1146668608,
              119249333028, 15400125776000, 2417814003691405,
              453536611741073664, 100178077459552487070,
              25735749696251388478720, 7608415981499790110521875,
              2564724413131659780025106432, 977834710569917222742633274504]
    for n, expected in enumerate(values, 1):
        assert permanent_ap_circulant(n, 0, 1) == expected
        if n <= 13:
            assert subset_permanent(circulant(n, 0, 1)) == expected
    counts["oeis_values"] = len(values)

    # Both sides are homogeneous of degree n: n+1 evaluations at B=1
    # determine the complete polynomial in A,B over the integers.
    counts["whole_polynomial_evaluations"] = 0
    for n in range(11):
        for a in range(n + 1):
            assert permanent_ap_circulant(n, a, 1) == subset_permanent(circulant(n, a, 1))
            counts["whole_polynomial_evaluations"] += 1

    counts["constant_matrices"] = 0
    for n in (0, 1, 2, 5, 12, 20):
        for a in (0, -2, 3):
            assert permanent_ap_circulant(n, a, 0) == factorial(n) * a**n
            counts["constant_matrices"] += 1

    assert permanent_ap_circulant(3, 1, 1) == 54
    for call in (lambda: permanent_staircase([1], [], 0),
                 lambda: permanent_ap_circulant(-1, 0, 1)):
        try:
            call()
        except ValueError:
            pass
        else:
            raise AssertionError("invalid input was not rejected")
    print(json.dumps({"status": "all passed", "seed": 3708,
                      "exact_instance_checks": sum(counts.values()),
                      "counts": counts, "input_validation_checks": 2}, indent=2))


if __name__ == "__main__":
    main()
